// child, case by case. The pictures were taken from 1.2.1 before any of its
// code was touched, so a refactor that changes a single pixel of a single
// nip fails here.
//
// A picture is the clip of a 32 x 20 bubble sampled at pixel centres: `#` is
// inside the path, `.` is outside. The defaults are the ones [Bubble] passes
// when nothing is set: radius 6, nip 8 x 10, nip radius 1, padding 8 x 6.

const _size = Size(32, 20);

BubbleClipper _clipper({
  BubbleNip nip = BubbleNip.no,
  bool showNip = true,
  double nipWidth = 8,
  double nipHeight = 10,
  double nipOffset = 0,
  double nipRadius = 1,
  bool stick = false,
  Radius radius = const Radius.circular(6),
  EdgeInsets padding = const EdgeInsets.fromLTRB(8, 6, 8, 6),
}) =>
    BubbleClipper(
      radius: radius,
      showNip: showNip,
      nip: nip,
      nipWidth: nipWidth,
      nipHeight: nipHeight,
      nipOffset: nipOffset,
      nipRadius: nipRadius,
      stick: stick,
      padding: padding,
    );

String _picture(Path path) {
  final picture = StringBuffer();
  for (var y = 0; y < _size.height; y++) {
    for (var x = 0; x < _size.width; x++) {
      picture.write(path.contains(Offset(x + 0.5, y + 0.5)) ? '#' : '.');
    }
    picture.writeln();
  }

  return picture.toString();
}

